/**
 * A tiny OpenAI-compatible mock provider, used by the unit, HTTP and
 * end-to-end tests. Scenario selection is driven by a `SCENARIO:<name>` marker
 * inside the test file that NeoSolver forwards.
 */

import http from 'node:http';
import path from 'node:path';
import { readFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { extractTestFile } from '../../src/prompt.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const EXPECTED_DIR = path.join(HERE, '..', 'fixtures', 'react', 'expected');

/** Read a directory tree into `{relativePath: content}` (utf8, byte-faithful). */
export function readTree(dir = EXPECTED_DIR, rel = '') {
  /** @type {Record<string,string>} */
  const files = {};
  const entries = readdirSync(path.join(dir, rel), { withFileTypes: true }).sort((a, b) =>
    a.name < b.name ? -1 : 1,
  );
  for (const entry of entries) {
    const child = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) Object.assign(files, readTree(dir, child));
    else files[child] = readFileSync(path.join(dir, child), 'utf8');
  }
  return files;
}

const asJson = (files, notes = '') => JSON.stringify({ files, notes });

function annotatedReply(files) {
  const blocks = Object.entries(files).map(([name, content]) => {
    const language = name.endsWith('.css') ? 'css' : name.endsWith('.html') ? 'html' : 'jsx';
    return `\`\`\`${language} ${name}\n${content}\`\`\``;
  });
  return `Here are the files:\n\n${blocks.join('\n\n')}\n`;
}

export function scenarioOf(testFile) {
  return (/SCENARIO:([a-z0-9_-]+)/i.exec(testFile ?? '')?.[1] ?? 'default').toLowerCase();
}

/** @returns {{content?: string, http?: object, failFirst?: object, delayMs?: number}} */
export function replyFor(testFile) {
  const scenario = scenarioOf(testFile);
  const expected = () => readTree(EXPECTED_DIR);

  switch (scenario) {
    case 'fenced':
      return { content: `\`\`\`json\n${asJson(expected())}\n\`\`\`` };

    case 'prose':
      return {
        content: `Sure — here is the solution you asked for.\n\n${asJson(expected())}\n\nLet me know if you want changes.`,
      };

    case 'garbage':
      return { content: 'I am sorry, I cannot help with that request. There is no JSON in this reply. ###' };

    case 'traversal':
      return { content: asJson({ '../../etc/passwd': 'pwned\n' }) };

    case 'absolute':
      return { content: asJson({ '/etc/passwd': 'pwned\n' }) };

    case 'dash':
      return { content: asJson({ '-rf': 'pwned\n' }) };

    case 'dotdot':
      return { content: asJson({ 'a/../../b': 'pwned\n' }) };

    case 'duplicate':
      return {
        content: JSON.stringify({
          files: [
            { path: 'App.jsx', content: 'first' },
            { path: 'App.jsx', content: 'second' },
          ],
        }),
      };

    case 'empty':
      return { content: '{"files":{}}' };

    case 'annotated':
      return { content: annotatedReply(expected()) };

    case 'single':
      return { content: `\`\`\`\n${expected()['App.jsx']}\n\`\`\`` };

    case 'echo': {
      // `testFile` is already the exact body that arrived (the mock extracts it
      // from the user message before dispatching). Echoing it back verbatim is
      // the byte-identity proof: with the `curl -d` newline bug this mismatches.
      return { content: asJson({ 'tests.js': testFile ?? '' }), notes: 'echo' };
    }

    case 'notes':
      return { content: asJson(expected(), 'generated by the mock provider') };

    case 'html':
      return {
        http: {
          status: 200,
          contentType: 'text/html',
          body: '<html><body><h1>502 Bad Gateway</h1><p>upstream is down</p></body></html>',
        },
      };

    case 'provider401':
      return { http: { status: 401, body: '{"error":{"message":"invalid api key"}}' } };

    case 'provider500':
      return { http: { status: 500, body: 'upstream exploded' } };

    case 'provider429':
      return {
        failFirst: { status: 429, times: 1, body: '{"error":{"message":"rate limited"}}' },
        content: asJson(expected()),
      };

    case 'slow':
      return { delayMs: 3000, content: asJson(expected()) };

    default:
      return { content: asJson(expected()) };
  }
}

/**
 * @param {{expectedDir?: string}} [options]
 * @returns {{server: import('node:http').Server, requests: Array<object>, failures: Map<string, number>, url: () => string}}
 */
export function createMockProvider({ expectedDir = EXPECTED_DIR } = {}) {
  const requests = [];
  const failures = new Map();
  void expectedDir;

  const server = http.createServer((req, res) => {
    const url = req.url ?? '';
    if (req.method !== 'POST' || !url.startsWith('/v1/chat/completions')) {
      res.writeHead(404, { 'content-type': 'application/json' });
      res.end('{"error":{"message":"mock provider only serves POST /v1/chat/completions"}}');
      return;
    }

    const chunks = [];
    req.on('data', (chunk) => chunks.push(chunk));
    req.on('end', () => {
      let payload = null;
      try {
        payload = JSON.parse(Buffer.concat(chunks).toString('utf8'));
      } catch {
        payload = null;
      }

      const messages = Array.isArray(payload?.messages) ? payload.messages : [];
      const userMessage =
        [...messages].reverse().find((message) => message?.role === 'user')?.content ?? '';
      const testFile = extractTestFile(userMessage);
      const reply = replyFor(testFile ?? '');
      requests.push({ model: payload?.model, testFile, messages, authorization: req.headers.authorization });

      const sendNow = () => {
        if (reply.failFirst) {
          const key = `failFirst:${reply.failFirst.status}`;
          const seen = failures.get(key) ?? 0;
          failures.set(key, seen + 1);
          if (seen < reply.failFirst.times) {
            res.writeHead(reply.failFirst.status, { 'content-type': 'application/json' });
            res.end(reply.failFirst.body);
            return;
          }
        }

        if (reply.http) {
          res.writeHead(reply.http.status, {
            'content-type': reply.http.contentType ?? 'application/json',
          });
          res.end(reply.http.body);
          return;
        }

        const body = JSON.stringify({
          id: 'chatcmpl-mock',
          object: 'chat.completion',
          created: Math.floor(Date.now() / 1000),
          model: payload?.model ?? 'mock',
          choices: [
            {
              index: 0,
              message: { role: 'assistant', content: reply.content ?? '' },
              finish_reason: 'stop',
            },
          ],
          usage: { prompt_tokens: 100, completion_tokens: 200, total_tokens: 300 },
        });
        res.writeHead(200, { 'content-type': 'application/json' });
        res.end(body);
      };

      if (reply.delayMs) setTimeout(sendNow, reply.delayMs);
      else sendNow();
    });
  });

  return {
    server,
    requests,
    failures,
    url: () => {
      const address = server.address();
      if (!address || typeof address === 'string') throw new Error('mock provider is not listening');
      return `http://127.0.0.1:${address.port}`;
    },
  };
}

/** Start a mock provider on an ephemeral (or given) port. */
export async function startMockProvider(port = 0) {
  const provider = createMockProvider();
  await new Promise((resolve, reject) => {
    provider.server.once('error', reject);
    provider.server.listen(port, '127.0.0.1', resolve);
  });
  return provider;
}
